//! 随包分发的 MCP / CLI 入口：生成可粘贴的 MCP 配置，以及本机命令行工具的
//! 安装与卸载。两者都只是把 App 包里已有的二进制接入用户环境，不复制推理
//! 运行时，也不改动任何第三方客户端配置。

use std::fs;
use std::path::{Path, PathBuf};

use serde::Serialize;
use voice_to_text_service::sidecar;

/// MCP 配置文本 + 它指向的可执行文件（供 UI 展示真实路径）。
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct McpConfigReply {
    pub config: String,
    pub command: String,
}

/// 命令行工具的安装状态。`path` 是链接/垫片位置，`target` 是 App 包内二进制。
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CliToolStatus {
    pub installed: bool,
    pub path: String,
    pub target: String,
    pub target_dir: String,
    pub path_ready: bool,
}

/// `~/.local/bin`（Windows 为 `%USERPROFILE%\.local\bin`）。
fn cli_link_dir() -> Result<PathBuf, String> {
    let home = if cfg!(windows) {
        std::env::var_os("USERPROFILE").or_else(|| std::env::var_os("HOME"))
    } else {
        std::env::var_os("HOME")
    };
    home.map(|home| PathBuf::from(home).join(".local").join("bin"))
        .ok_or_else(|| "Cannot locate the home folder.".to_owned())
}

fn cli_link_path(dir: &Path) -> PathBuf {
    if cfg!(windows) {
        dir.join("local-transcribe.cmd")
    } else {
        dir.join(sidecar::executable_name(sidecar::CLI_BINARY))
    }
}

/// Windows 没有免提权的符号链接，用一个固定内容的 `.cmd` 垫片代替。
#[cfg(windows)]
fn shim_content(target: &Path) -> String {
    format!(
        "@echo off\r\nrem generated by Local Transcribe\r\n\"{}\" %*\r\n",
        target.display()
    )
}

/// 是否由本应用生成：macOS/Linux 看符号链接指向，Windows 看垫片标记。
fn is_ours(link: &Path, target: &Path) -> bool {
    if cfg!(windows) {
        match fs::read_to_string(link) {
            Ok(text) => {
                text.contains("rem generated by Local Transcribe")
                    && text.contains(&target.to_string_lossy().to_string())
            }
            Err(_) => false,
        }
    } else {
        match fs::read_link(link) {
            Ok(pointed) => pointed == target,
            Err(_) => false,
        }
    }
}

/// 安装（幂等）。已存在但不属于本应用的条目一律不覆盖。
fn install_in(dir: &Path, target: &Path) -> Result<(), String> {
    if !target.is_file() {
        return Err(format!("This build does not include {}.", target.display()));
    }
    fs::create_dir_all(dir).map_err(|error| format!("Cannot create {}: {error}", dir.display()))?;
    let link = cli_link_path(dir);
    if link.exists() || fs::symlink_metadata(&link).is_ok() {
        if is_ours(&link, target) {
            return Ok(());
        }
        return Err(format!(
            "{} already exists and was not created by Local Transcribe; remove it first.",
            link.display()
        ));
    }
    #[cfg(windows)]
    {
        fs::write(&link, shim_content(target))
            .map_err(|error| format!("Cannot write {}: {error}", link.display()))?;
        Ok(())
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(target, &link)
            .map_err(|error| format!("Cannot link {}: {error}", link.display()))
    }
}

/// 卸载（只处理本应用生成的条目），返回被移除的路径。
fn uninstall_in(
    dir: &Path,
    target: &Path,
    remove: &dyn Fn(&Path) -> Result<(), String>,
) -> Result<Option<PathBuf>, String> {
    let link = cli_link_path(dir);
    if !(link.exists() || fs::symlink_metadata(&link).is_ok()) {
        return Ok(None);
    }
    if !is_ours(&link, target) {
        return Err(format!(
            "{} was not created by Local Transcribe; leaving it untouched.",
            link.display()
        ));
    }
    remove(&link)?;
    Ok(Some(link))
}

fn status_for(dir: &Path, target: PathBuf) -> CliToolStatus {
    let link = cli_link_path(dir);
    let installed = is_ours(&link, &target);
    let path_ready = std::env::var_os("PATH")
        .map(|paths| std::env::split_paths(&paths).any(|entry| entry == dir))
        .unwrap_or(false);
    CliToolStatus {
        installed,
        path: link.to_string_lossy().into_owned(),
        target: target.to_string_lossy().into_owned(),
        target_dir: dir.to_string_lossy().into_owned(),
        path_ready,
    }
}

#[tauri::command]
pub fn mcp_config() -> Result<McpConfigReply, String> {
    let command = sidecar::bundled_binary(sidecar::MCP_BINARY)?;
    let config = sidecar::render_mcp_config(&command)?;
    Ok(McpConfigReply {
        config,
        command: command.to_string_lossy().into_owned(),
    })
}

#[tauri::command]
pub fn cli_tool_status() -> Result<CliToolStatus, String> {
    let dir = cli_link_dir()?;
    let target = sidecar::bundled_binary(sidecar::CLI_BINARY)?;
    Ok(status_for(&dir, target))
}

#[tauri::command]
pub fn install_cli_tool() -> Result<CliToolStatus, String> {
    let dir = cli_link_dir()?;
    let target = sidecar::bundled_binary(sidecar::CLI_BINARY)?;
    install_in(&dir, &target)?;
    Ok(status_for(&dir, target))
}

#[tauri::command]
pub fn uninstall_cli_tool() -> Result<CliToolStatus, String> {
    let dir = cli_link_dir()?;
    let target = sidecar::bundled_binary(sidecar::CLI_BINARY)?;
    uninstall_in(&dir, &target, &|path| {
        voice_to_text_core::move_to_trash(path)
    })?;
    Ok(status_for(&dir, target))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn scratch() -> PathBuf {
        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let dir = std::env::temp_dir().join(format!("lt-cli-tool-{}-{now}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn fake_target(dir: &Path) -> PathBuf {
        let target = dir.join(sidecar::executable_name(sidecar::CLI_BINARY));
        fs::write(&target, b"binary").unwrap();
        target
    }

    #[test]
    fn install_is_idempotent_and_reports_the_link_path() {
        let dir = scratch();
        let bin = dir.join("bin");
        let target = fake_target(&dir);
        install_in(&bin, &target).unwrap();
        install_in(&bin, &target).unwrap();
        let link = cli_link_path(&bin);
        assert!(
            is_ours(&link, &target),
            "link must point at the bundled CLI"
        );
    }

    #[test]
    fn install_refuses_to_overwrite_a_foreign_entry() {
        let dir = scratch();
        let bin = dir.join("bin");
        fs::create_dir_all(&bin).unwrap();
        let target = fake_target(&dir);
        let link = cli_link_path(&bin);
        fs::write(&link, b"someone else's tool").unwrap();
        let error = install_in(&bin, &target).unwrap_err();
        assert!(error.contains("not created by Local Transcribe"), "{error}");
        assert_eq!(fs::read(&link).unwrap(), b"someone else's tool");
    }

    #[test]
    fn uninstall_only_removes_our_own_link() {
        let dir = scratch();
        let bin = dir.join("bin");
        let target = fake_target(&dir);
        install_in(&bin, &target).unwrap();
        let removed = std::cell::RefCell::new(Vec::new());
        let outcome = uninstall_in(&bin, &target, &|path| {
            removed.borrow_mut().push(path.to_path_buf());
            fs::remove_file(path).map_err(|error| error.to_string())
        })
        .unwrap();
        assert_eq!(outcome, Some(cli_link_path(&bin)));
        assert_eq!(removed.borrow().len(), 1);
        assert!(fs::symlink_metadata(cli_link_path(&bin)).is_err());
    }

    #[test]
    fn uninstall_leaves_a_foreign_entry_alone() {
        let dir = scratch();
        let bin = dir.join("bin");
        fs::create_dir_all(&bin).unwrap();
        let target = fake_target(&dir);
        let link = cli_link_path(&bin);
        fs::write(&link, b"unrelated").unwrap();
        let error = uninstall_in(&bin, &target, &|path| {
            fs::remove_file(path).map_err(|error| error.to_string())
        })
        .unwrap_err();
        assert!(error.contains("leaving it untouched"), "{error}");
        assert!(link.is_file());
    }

    #[test]
    fn install_reports_a_missing_bundled_binary() {
        let dir = scratch();
        let bin = dir.join("bin");
        let missing = dir.join("nope");
        let error = install_in(&bin, &missing).unwrap_err();
        assert!(error.contains("does not include"), "{error}");
    }
}
